import { CloudDownload, Download, FileCheck2, FileUp, FileX2, Lock, Trash2 } from 'lucide-react'
import { useRef, useState } from 'react'
import NeedBusiness from '../components/NeedBusiness'
import { Bar, Chip, ErrorBox, PageHead, Panel, Spinner, Stat, statusTone } from '../components/ui'
import { api, downloadBlob } from '../lib/api'
import { useAuth } from '../lib/auth'
import { pct } from '../lib/format'
import { useAction, useApi } from '../lib/hooks'
import type { Business, DocChecklist, DocItem } from '../lib/types'

const STATUS_TEXT: Record<string, string> = {
  uploaded: 'Uploaded · encrypted', fetched: 'Fetched automatically', fetchable: 'Can auto-fetch', auto: 'Generated by ARTHA',
  after_sanction: 'Only after sanction', missing: 'Please upload',
}

function View({ b }: { b: Business }) {
  const { user } = useAuth()
  const { data, error, loading, reload } = useApi<DocChecklist>(`/businesses/${b.id}/documents`, [b.id])
  const { busy, error: actErr, run } = useAction()
  const input = useRef<HTMLInputElement>(null)
  const [target, setTarget] = useState<string | null>(null)

  const pick = (doc: string) => { setTarget(doc); input.current?.click() }
  const upload = (f: File) => target && run(async () => {
    if (f.size > 2 * 1024 * 1024) throw new Error('File too large (max 2 MB)')
    const form = new FormData()
    form.append('doc_type', target)
    form.append('file', f)
    await api(`/businesses/${b.id}/documents`, { method: 'POST', form })
    await reload()
  })
  const del = (d: DocItem) => d.document_id && confirm(`Delete ${d.label}? The encrypted file will be erased.`) &&
    run(async () => { await api(`/documents/${d.document_id}`, { method: 'DELETE' }); await reload() })

  if (loading && !data) return <Spinner label="Document Agent assembling checklist" />
  if (error) return <ErrorBox msg={error} onRetry={reload} />
  if (!data) return null
  const s = data.stats
  return (
    <div className="space-y-5">
      <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <Stat label="Documents needed" value={`${s.required}`} sub={`instead of ~${s.traditional} the usual way`} tone="green" />
        <Stat label="Ready" value={s.ready} sub="Uploaded, fetched or generated" />
        <Stat label="Auto-fetchable" value={s.auto_fetchable} sub="DigiLocker / Account Aggregator" tone="violet" />
        <Stat label="You must upload" value={s.owner_must_upload} sub={`File ${pct(s.completeness)} complete`} tone={s.owner_must_upload ? 'amber' : 'green'} />
      </div>
      <Panel title={`Checklist for ${data.schemes.length ? data.schemes.join(' + ').toUpperCase() : 'core KYC'}`} icon={<FileCheck2 className="h-3.5 w-3.5" />}
        right={<div className="w-40"><Bar value={s.completeness} tone="green" /></div>}>
        <input ref={input} type="file" accept="application/pdf,image/png,image/jpeg" className="hidden"
          onChange={(e) => { const f = e.target.files?.[0]; if (f) upload(f); e.target.value = '' }} />
        <ErrorBox msg={actErr} />
        <div className="overflow-x-auto">
          <table className="w-full min-w-[640px] text-sm">
            <thead><tr className="label text-left"><th className="py-2 pr-3 font-normal">Document</th><th className="font-normal">Needed for</th><th className="font-normal">Status</th><th className="text-right font-normal">Action</th></tr></thead>
            <tbody>
              {data.items.map((d) => (
                <tr key={d.doc_type} className="table-row">
                  <td className="py-2.5 pr-3">
                    <div className="flex items-center gap-2">
                      {d.status === 'missing' ? <FileX2 className="h-4 w-4 text-neon-red" /> : <FileCheck2 className="h-4 w-4 text-neon-green" />}
                      <span className="text-slate-100">{d.label}</span>
                    </div>
                  </td>
                  <td className="text-xs text-slate-400">{d.required_by.map((r) => (r === 'core' ? 'All loans' : r)).join(', ')}</td>
                  <td><Chip tone={statusTone(d.status)}>{STATUS_TEXT[d.status] ?? d.status}</Chip>{d.auto_source && d.status !== 'uploaded' && <span className="ml-1 font-mono text-[10px] text-slate-500">via {d.auto_source}</span>}</td>
                  <td className="text-right">
                    <div className="flex justify-end gap-1.5">
                      {d.document_id && <button className="btn-ghost !px-2 !py-1" title="Download (decrypted for you only)" disabled={busy}
                        onClick={() => run(() => downloadBlob(`/documents/${d.document_id}/download`, `${d.doc_type}`))}><Download className="h-3.5 w-3.5" /></button>}
                      {d.document_id && user?.role === 'entrepreneur' && <button className="btn-ghost !px-2 !py-1 hover:!border-neon-red/50" title="Delete" disabled={busy} onClick={() => del(d)}><Trash2 className="h-3.5 w-3.5" /></button>}
                      {['missing', 'uploaded'].includes(d.status) && <button className="btn-ghost !py-1 text-xs" disabled={busy} onClick={() => pick(d.doc_type)}><FileUp className="h-3.5 w-3.5" /> {d.status === 'missing' ? 'Upload' : 'Replace'}</button>}
                      {d.status === 'fetchable' && <span className="inline-flex items-center gap-1 text-[11px] text-cyan-300"><CloudDownload className="h-3.5 w-3.5" /> fetched on approval</span>}
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </Panel>
      <Panel>
        <div className="flex items-start gap-3 text-sm text-slate-400">
          <Lock className="mt-0.5 h-5 w-5 shrink-0 text-neon-green" />
          <p>Files are checked by their content signature (PDF, PNG or JPEG only, max 2 MB), encrypted with your personal AES-256 key and never cached
            by the browser. Lenders can open them only while your consent for <span className="font-mono text-slate-300">documents</span> is active, and every view appears in your access log.</p>
        </div>
      </Panel>
    </div>
  )
}

export default function Documents() {
  return (
    <div>
      <PageHead kicker="Document Agent" title="Document Vault">
        From 15–20 documents and months of running around to a short, auto-assembled list.
      </PageHead>
      <NeedBusiness>{(b) => <View b={b} />}</NeedBusiness>
    </div>
  )
}
